function HqBadge() {
  return <span className="hq">OET HQ</span>;
}

function planApiTier(tier: TierKey) {
  return tier === "FREE" ? "STARTER" : tier;
}

function portalAssignUrl(plan: StaticPlan) {
  return `/portal?selectTier=${encodeURIComponent(planApiTier(plan.tier))}`;
}

function isBackendPlanId(planId: string) {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(planId);
}

function buildSelectPlanBody(plan: StaticPlan) {
  return { tier: planApiTier(plan.tier) };
}

async function assignSelectedPlan(plan: StaticPlan, token: string) {
  await apiFetch("/subscriptions/select-plan", {
    method: "POST",
    token,
    body: buildSelectPlanBody(plan)
  });
}

async function startStripeCheckout(planId: string, userId: string, token: string) {
  const response = await apiFetch<PurchaseIntentResponseDto>("/subscriptions/purchases", {
    method: "POST",
    token,
    body: {
      userId,
      planId,
      provider: "STRIPE"
    }
  });

  if (!response.checkoutUrl) {
    throw new Error("Could not start checkout");
  }

  window.location.href = response.checkoutUrl;
}

