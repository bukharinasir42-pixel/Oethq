type WebsiteUpgradePlansModalProps = {
  open: boolean;
  onOpenChange: (open: boolean) => void;
};

/** Portal upgrade dialog: same home-page pricing cards, free plan excluded. */
export function WebsiteUpgradePlansModal({ open, onOpenChange }: WebsiteUpgradePlansModalProps) {
  const router = useRouter();
  const { token, profile } = useSession();
  const [displayPlans, setDisplayPlans] = useState<StaticPlan[]>(STATIC_PLANS);
  const [plansNote, setPlansNote] = useState<string | null>(null);
  const [selectingTier, setSelectingTier] = useState<TierKey | null>(null);

  useEffect(() => {
    if (!open) return;

    let cancelled = false;
    (async () => {
      try {
        const rows = await apiFetch<PlanDto[]>("/plans", { token: null });
        if (cancelled) return;
        if (rows?.length) {
          setDisplayPlans(mergePlansFromApi(rows));
          setPlansNote(null);
        }
      } catch {
        if (!cancelled) {
          setPlansNote("Showing typical pricing — live catalog unavailable.");
        }
      }
    })();

    return () => {
      cancelled = true;
    };
  }, [open]);

  const paidPlans = useMemo(() => displayPlans.filter((plan) => plan.tier !== "FREE"), [displayPlans]);

  const planKey = useMemo(
    () =>
      paidPlans
        .map(
          (p) =>
            `${p.id}-${p.priceAmount ?? "0"}-${p.durationDays}-${p.pastPaperLimit}-${p.readingLimit}-${p.listeningLimit}`
        )
        .join("|"),
    [paidPlans]
  );

  const handleUpgradePurchase = useCallback(
    async (plan: StaticPlan) => {
      if (!token || !profile) {
        toast.error("Please sign in again to upgrade.");
        return;
      }

      if (!isBackendPlanId(plan.id)) {
        toast.error("Live pricing is still loading. Please try again in a moment.");
        return;
      }

      setSelectingTier(plan.tier);
      try {
        const sub = await apiFetch<{ accessGranted?: boolean; plan?: { tier?: string } | null }>(
          `/subscriptions/status?userId=${encodeURIComponent(profile.id)}`,
          { token }
        );
        if (sub.accessGranted && sub.plan?.tier && sub.plan.tier !== "STARTER") {
          toast.message("You already have an active paid plan.");
          onOpenChange(false);
          router.push("/portal");
          return;
        }

        await startStripeCheckout(plan.id, profile.id, token);
      } catch (error: unknown) {
        toast.error(error instanceof Error ? error.message : "Unable to start checkout");
      } finally {
        setSelectingTier(null);
      }
    },
    [onOpenChange, profile, router, token]
  );

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="upgrade-plans-dialog max-h-[min(92vh,820px)] w-[min(1080px,calc(100vw-1.5rem))] max-w-none overflow-hidden border-0 bg-transparent p-0 shadow-none sm:rounded-[22px]">
        <div
          className={cn(
            upgradeModalSans.className,
            upgradeModalSans.variable,
            upgradeModalInter.variable,
            upgradeModalDisplay.variable,
            "oethq-home oethq-rest upgrade-plans-home bg-white text-slate-900"
          )}
        >
          <section className="pt-scope pkg-cards-section pt-courses upgrade-plans-section">
            <div className="wrap">
              <DialogHeader className="head space-y-0">
                <div className="eyebrow">Upgrade your access</div>
                <DialogTitle asChild>
                  <h1>
                    Choose Your <span className="grad">Clearance System</span>
                  </h1>
                </DialogTitle>
                <DialogDescription asChild>
                  <p className="sub">
                    Every tier is engineered around one outcome: <strong>Grade B on your first attempt.</strong>
                  </p>
                </DialogDescription>
              </DialogHeader>

              {plansNote ? (
                <p className="mx-auto mt-4 max-w-xl rounded-xl border border-amber-200/80 bg-amber-50/90 px-4 py-2 text-xs text-amber-950">
                  {plansNote}
                </p>
              ) : null}

              <div className="cards cards-3" key={planKey}>
                {paidPlans.map((plan) => (
                  <PackageCard
                    key={`${plan.tier}-${plan.id}`}
                    plan={plan}
                    onPurchase={handleUpgradePurchase}
                    isSelecting={selectingTier === plan.tier}
                  />
                ))}
              </div>

              <p className="guarantee">
                <b>Upgrade any time</b> — pay only the difference. Secure checkout · Instant access.
              </p>
            </div>
          </section>
        </div>
      </DialogContent>
    </Dialog>
  );
}
